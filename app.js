let lb = null;   // {photos, i, sci}

function openLightbox(photos, i, sci){
  if (!photos || !photos.length) return;
  lb = {photos, i, sci};
  const el = $('#lb');
  el.hidden = false;
  el.innerHTML = `
    <button class="lbx" aria-label="Close photograph">✕</button>
    <button class="lbnav lbprev" aria-label="Previous photograph">‹</button>
    <figure class="lbfig">
      <img id="lbimg" alt="">
      <figcaption>
        <div class="lbname">${sci}</div>
        <div class="lbcred" id="lbcred"></div>
        <div class="lbcount" id="lbcount"></div>
      </figcaption>
    </figure>
    <button class="lbnav lbnext" aria-label="Next photograph">›</button>`;
  el.querySelector('.lbx').onclick = closeLightbox;
  el.querySelector('.lbprev').onclick = e => { e.stopPropagation(); step(-1); };
  el.querySelector('.lbnext').onclick = e => { e.stopPropagation(); step(1); };
  // clicking the backdrop closes; clicking the photo itself must not
  el.onclick = e => { if (e.target === el) closeLightbox(); };
  el.querySelector('.lbfig').onclick = e => e.stopPropagation();
  document.body.classList.add('lbopen');
  paintLightbox();
  el.querySelector('.lbx').focus();
}

function paintLightbox(){
  if (!lb) return;
  const p = lb.photos[lb.i];
  const img = $('#lbimg');
  img.src = p.url;
  img.alt = `${lb.sci} — photograph ${lb.i + 1} of ${lb.photos.length}`;
  // credit and licence travel with each photograph, never the set
  $('#lbcred').textContent = [p.credit, p.licence ? p.licence.toUpperCase() : '']
    .filter(Boolean).join(' · ') || 'Credit unavailable';
  $('#lbcount').textContent = `${lb.i + 1} / ${lb.photos.length}`;
  const one = lb.photos.length < 2;
  $('#lb').querySelectorAll('.lbnav').forEach(b => b.hidden = one);
}

function step(d){
  if (!lb) return;
  lb.i = (lb.i + d + lb.photos.length) % lb.photos.length;   // wraps both ways
  paintLightbox();
}

function closeLightbox(){
  lb = null;
  const el = $('#lb');
  el.hidden = true; el.innerHTML = '';
  document.body.classList.remove('lbopen');
}

document.addEventListener('keydown', e => {
  if (!lb) return;
  if (e.key === 'Escape') closeLightbox();
  else if (e.key === 'ArrowRight') step(1);
  else if (e.key === 'ArrowLeft') step(-1);
});

