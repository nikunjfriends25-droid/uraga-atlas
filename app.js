/** Frame a lat/lon bounding box. Leaflet owns the projection and the
 *  animation; we only decide what should be visible. */
/** Padding that reflects what is actually VISIBLE. The filters panel, the
 *  region panel and the dock all overlay the map rather than shrinking it, so
 *  symmetric padding centres a region behind them — the user saw a selected
 *  country sitting half under the dock. */
function viewPadding(){
  const w = map.getSize().x, h = map.getSize().y;
  let left  = $('#panel').classList.contains('closed') ? 14 : $('#panel').offsetWidth + 18;
  let right = $('#rgnpanel').classList.contains('closed') ? 14 : $('#rgnpanel').offsetWidth + 18;
  const rep = $('#report').classList.contains('on') ? $('#report').offsetWidth : 0;
  right += rep;
  let bottom = $('#dock').classList.contains('closed') ? 52 : $('#dock').offsetHeight + 18;
  // on a narrow window the panels can cover most of the map; refuse to pad
  // past what is left or Leaflet has nothing to fit into
  if (left + right > w * 0.75){ left = right = 14; }
  // an expanded dock can claim ~78% of the height; clamp rather than discard,
  // so the region still lands in the strip above it instead of behind it
  if (bottom > h * 0.55) bottom = Math.round(h * 0.55);
  return {paddingTopLeft: L.point(left, 24), paddingBottomRight: L.point(right, bottom)};
}

function fitBounds(bounds, maxZoom = 12){
  if (!bounds || !bounds.isValid()) return;
  // animate:false is load-bearing. Leaflet's zoom animation is driven by
  // requestAnimationFrame; in a throttled or backgrounded tab it starts and
  // never finishes, so the camera silently never arrives at the region. User
  // -driven zoom (buttons, wheel) keeps its animation — only programmatic
  // framing is forced to apply immediately.
  map.fitBounds(bounds, {...viewPadding(), maxZoom, animate:false});
}

/** Frame every occurrence point of the selected species. Ranges vary from a
 *  single hill to the whole subcontinent, so this is fitted, not fixed. */
function fitToPoints(pts){
  if (!pts || !pts.length) return;      // nothing to frame: leave the camera
  fitBounds(L.latLngBounds(pts.map(p => [p.lat, p.lon])));
}

// zoom changes which cluster grid is appropriate; only redraw when it flips
map.on('zoomend', () => {
  hideTip();
  if (picked) return;
  const lv = levelFor(map.getZoom());
  const flipped = lv !== state.z;
  state.z = lv;
  // bubble radius and heat class breaks both depend on zoom, so the map is
  // redrawn on every zoom; a full render() (which rebuilds the panel) is only
  // needed when the grid level itself changes
  if (flipped) return render();
  drawMap(); drawRegion(); drawLegend();
});
map.on('movestart', hideTip);
map.on('click', () => $('#rc2').classList.remove('on'));

