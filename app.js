/* ── filtering ────────────────────────────────────────── */
function matches(sp){
  if (regionIds && !regionIds.has(sp.id)) return false;
  if (state.grp.size && !state.grp.has(sp.grp)) return false;
  if (state.iucn.size && !state.iucn.has(sp.iucn)) return false;
  if (state.q){
    const q = state.q.toLowerCase();
    if (!(sp.sci.toLowerCase().includes(q) || (sp.com || '').toLowerCase().includes(q) ||
          (sp.fam || '').toLowerCase().includes(q))) return false;
  }
  return true;
}
function keep(key){
  const [g, i] = key.split('|');
  if (state.grp.size && !state.grp.has(g)) return false;
  if (state.iucn.size && !state.iucn.has(i)) return false;
  return true;
}

