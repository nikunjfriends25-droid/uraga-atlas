/* ── busy indicator ───────────────────────────────────────
 * Photographs and occurrence points are fetched live and take a few seconds,
 * during which the map is simply empty. Say so rather than looking broken. */
let busyDepth = 0;
function setBusy(on, label){
  busyDepth = Math.max(0, busyDepth + (on ? 1 : -1));
  const el = $('#busy');
  el.hidden = busyDepth === 0;
  if (busyDepth && label) el.querySelector('.busylbl').textContent = label;
}
