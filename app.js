/* Clusters are precomputed at four grid resolutions. Pick whichever leaves the
 * cell centres far enough apart to read at the current zoom: Leaflet's world is
 * 256·2^z px across 360°, so spacing in px = cellDegrees · 256·2^z / 360.
 * Below ~45px the bubbles start merging into one another. */
const CELLS_FALLBACK = {z0:4.4, z1:2.2, z2:1.1, z3:0.5};
const LEVEL_KEYS = ['z0', 'z1', 'z2', 'z3'];
const pxPerDeg = z => 256 * Math.pow(2, z) / 360;
const cellDeg = lv => ((DATA && DATA.cells) || CELLS_FALLBACK)[LEVEL_KEYS[lv]];

/* Bubbles must be big enough to hold a number; heatmap cells only have to be
   visible. So the heatmap can run a much finer grid at the same zoom — which
   is most of why it resolves more detail than the bubbles ever did. */
const FLOOR = {heat: 9, clusters: 45};

function levelFor(z, view = state.view){
  // the finest grid whose spacing still clears the readability floor
  for (let i = LEVEL_KEYS.length - 1; i >= 0; i--){
    if (cellDeg(i) * pxPerDeg(z) >= FLOOR[view]) return i;
  }
  return 0;
}

/* Pale straw → amber → burnt sienna. Sequential, single family, and
   deliberately clear of the red (--occ) that marks occurrence points. */
const HEAT = ['#FEF0C0', '#FCD97E', '#F8BE3C', '#F59E0B', '#D97706', '#9A3412'];

/** Class breaks by quantile, not equal interval. Cell counts are savagely
 *  skewed — at 2.2° the median cell holds ~107 records and the largest 8,438 —
 *  so equal intervals would paint one hot cell above a uniform floor.
 *  Returns the inclusive upper bound of each class. */
function heatBreaks(values){
  const v = values.filter(n => n > 0).sort((a, b) => a - b);
  if (!v.length) return [];
  const out = [];
  for (let i = 1; i <= HEAT.length; i++){
    const q = v[Math.min(v.length - 1, Math.floor(v.length * i / HEAT.length))];
    // drop duplicate bounds, or a long tail of 1s swallows several classes
    if (!out.length || q > out[out.length - 1]) out.push(q);
  }
  out[out.length - 1] = v[v.length - 1];
  return out;
}
/** Darkest classes always win the top of the ramp, however many survive. */
function heatColour(n, breaks){
  const i = breaks.findIndex(b => n <= b);
  const cls = i < 0 ? breaks.length - 1 : i;
  return HEAT[HEAT.length - breaks.length + cls];
}

/** Bubble radius, bounded by the room the grid actually leaves at this zoom.
 *  Area-proportional would be honest but unreadable across a 1–25,000 range,
 *  so this is sqrt-scaled against the largest cell currently drawn; the label
 *  carries the exact number. */
function clusterRadius(n, nmax, zoom, cellDegrees){
  const spacing = cellDegrees * pxPerDeg(zoom);
  const maxR = Math.max(12, Math.min(27, spacing * 0.46));
  const minR = Math.min(9.5, maxR * 0.6);
  return minR + (maxR - minR) * Math.sqrt(n / Math.max(nmax, 1));
}

