/** The grid to draw: the corpus level, or — when a region is selected — that
 *  region's OWN grid, so the map is genuinely scoped to the selection instead
 *  of showing the whole corpus behind an outline.
 *
 *  Region grids are stored at the finest cell size, and every coarser level is
 *  a power-of-two multiple of it, so aggregating up is exact: no point moves
 *  cell and no count is estimated. Cells stay keyed group|status, so the
 *  taxonomic-group and status filters remain exact inside a region too.
 */
function cellsForView(){
  if (!region || !region.cells){
    viewCell = cellDeg(state.z);
    return DATA.levels[LEVEL_KEYS[state.z]];
  }
  // A selected region carries its own grid at an adaptive fine base. Pick the
  // display cell from the ACTUAL zoom so zooming in re-grids finer (down to the
  // stored base), instead of being pinned at the corpus 0.55°.
  const want = 26 / pxPerDeg(map.getZoom());        // aim for ~26px cells
  const factor = Math.max(1, Math.round(want / region.cell));
  viewCell = region.cell * factor;
  const acc = new Map();
  for (const c of region.cells){
    const kx = Math.floor(c.k[0] / factor), ky = Math.floor(c.k[1] / factor);
    const id = kx + ',' + ky;
    let e = acc.get(id);
    if (!e){ e = {x: (kx + 0.5) * viewCell, y: (ky + 0.5) * viewCell, b: {}}; acc.set(id, e); }
    for (const k in c.b) e.b[k] = (e.b[k] || 0) + c.b[k];
  }
  return [...acc.values()];
}

function drawMap(){
  // The corpus grid is hidden while an AOI is being drawn/queried AND while an
  // AOI is applied: a custom area is defined by its outline, and the corpus grid
  // would show its species' records across ALL of India, not inside the boundary.
  if (window.__aoiDrawing || (region && region.aoi)){
    pointLayer.clearLayers(); clusterLayer.clearLayers();
    if (region && region.aoi && !window.__aoiDrawing){
      $('#r-occ').textContent = fmt(region.nrec);
      $('#r-cl').textContent = '—';
      $('#r-sp').textContent = fmt(region.sp.length);
      $('#foot').textContent = `${region.name} · ${fmt(region.sp.length)} species`;
      drawDock(region.nrec, 0);
    }
    return;
  }
  if (!picked) rangeLayer.clearLayers();
  // regionLayer is owned by drawRegion() and must NOT be cleared here: the
  // zoomend path calls drawMap() on its own, which would wipe the outline of
  // the selected region every time the map zoomed.
  if (picked) return drawSpeciesMap();
  pointLayer.clearLayers();
  clusterLayer.clearLayers();

  const cells = cellsForView();
  const zoom = map.getZoom();
  // count each cell once: radii and class breaks both need the whole set
  const counts = cells.map(c => {
    let n = 0;
    for (const k in c.b) if (keep(k)) n += c.b[k];
    return n;
  });

  const total = counts.reduce((a, b) => a + b, 0);
  const shown = counts.filter(n => n).length;
  state.breaks = state.view === 'heat' ? heatBreaks(counts) : null;

  if (state.view === 'heat') drawHeatCells(cells, counts);
  else drawBubbles(cells, counts, zoom);

  $('#r-occ').textContent = fmt(total);
  $('#r-cl').textContent = fmt(shown);
  $('#r-sp').textContent = fmt(INDEX.filter(matches).length);
  $('#foot').textContent = region
    ? `${region.name} · ${fmt(region.sp.length)} species`
    : `${fmt(DATA.stats.occ)} records · ${fmt(DATA.stats.species)} species`;
  drawDock(total, shown);
}

/** One filled rectangle per grid cell. The data IS a grid, so this draws
 *  exactly what we hold — no interpolation, and no overlap to manage. */
function drawHeatCells(cells, counts){
  const half = viewCell / 2;
  const breaks = state.breaks;
  cells.forEach((c, i) => {
    const n = counts[i];
    if (!n) return;
    const rect = L.rectangle(
      [[c.y - half, c.x - half], [c.y + half, c.x + half]], {
        stroke: false, fillColor: heatColour(n, breaks), fillOpacity: .78,
        className: 'heatcell',
      });
    rect.bindTooltip(`<b>${fmt(n)}</b> occurrence record${n === 1 ? '' : 's'}<br>
      <span class="dim">${viewCell.toFixed(2)}° cell · click to zoom in</span>`,
      {direction:'top', sticky:true, className:'clutip'});
    rect.on('click', () => map.setView([c.y, c.x],
      Math.min(17, map.getZoom() + 2), {animate:false}));
    clusterLayer.addLayer(rect);
  });
}

function drawBubbles(cells, counts, zoom){
  const nmax = Math.max(1, ...counts);
  cells.forEach((c, i) => {
    const n = counts[i];
    if (!n) return;
    const r = clusterRadius(n, nmax, zoom, viewCell);
    const label = n > 999 ? (n / 1000).toFixed(n > 9999 ? 0 : 1) + 'k' : n;
    const m = L.marker([c.y, c.x], {
      icon: L.divIcon({
        className: 'clui',
        // size the type to the label so "25.0k" does not spill out of a disc
        // sized for "42" (bold digits run ~0.62em wide)
        html: `<span class="clud" style="width:${r*2}px;height:${r*2}px;
                 font-size:${Math.max(7.5, Math.min(r * 0.8,
                   (r * 1.8) / (String(label).length * 0.62))).toFixed(1)}px">${label}</span>`,
        iconSize: [r*2, r*2], iconAnchor: [r, r],
      }),
      keyboard: false,
    });
    m.bindTooltip(`<b>${fmt(n)}</b> occurrence record${n === 1 ? '' : 's'}<br>
      <span class="dim">click to zoom in</span>`,
      {direction:'top', offset:[0,-r], className:'clutip'});
    m.on('click', () => map.setView([c.y, c.x], Math.min(17, map.getZoom() + 2), {animate:false}));
    clusterLayer.addLayer(m);
  });
}

function drawSpeciesMap(){
  clusterLayer.clearLayers();
  pointLayer.clearLayers();
  const pts = live ? live.points : [];
  // Records at the SAME coordinate stack into one dot — a species known from a
  // single locality can have many records at one point (Cyrtodactylus
  // bhupathyi: 6 records, 1 location). Group coincident records so the map
  // shows one marker carrying the count, rather than looking like a single
  // record when there are several.
  const groups = new Map();
  pts.forEach(rec => {
    const key = rec.lat.toFixed(4) + ',' + rec.lon.toFixed(4);
    let g = groups.get(key);
    if (!g){ g = {lat: rec.lat, lon: rec.lon, recs: []}; groups.set(key, g); }
    g.recs.push(rec);
  });
  window.__locations = groups.size;
  groups.forEach(g => {
    const n = g.recs.length;
    const marine = g.recs[0].src === 'OBIS';
    const r = n > 1 ? Math.min(11, 5 + Math.sqrt(n) * 1.4) : 5;
    const c = L.circleMarker([g.lat, g.lon], {
      radius: r, weight: 1.2, color: '#fff', opacity: .85,
      fillColor: marine ? '#2563EB' : '#EF4444', fillOpacity: .9, className: 'occpt',
    });
    if (n > 1){
      c.bindTooltip(`<b>${fmt(n)}</b> records at this location`,
        {direction: 'top', className: 'clutip'});
    }
    // click shows the first record, noting how many share the spot
    c.on('click', ev => { L.DomEvent.stopPropagation(ev);
      showRecord(g.recs[0], ev.originalEvent, n); });
    pointLayer.addLayer(c);
  });
  $('#r-occ').textContent = fmt((live && live.total) ?? picked.n);
  $('#r-sp').textContent = '1';
  $('#r-cl').textContent = '—';
  $('#foot').textContent = `${picked.sci} · ${fmt(picked.n)} records`;
  drawDock(picked.n, 0);
}

